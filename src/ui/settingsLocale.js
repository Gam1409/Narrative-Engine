/** Translate only fixed template text, never prompts, IDs or runtime payloads. */
export function bindSettingsLocale(root) {
    const entries = [];
    const attributes = [];
    for (const option of root.querySelectorAll('option:not([value])')) {
        option.setAttribute('value', option.textContent);
    }
    const walker = root.ownerDocument.createTreeWalker(root, 4);
    while (walker.nextNode()) {
        const node = walker.currentNode;
        if (node.parentElement.closest('textarea, pre, code, script, style')) continue;
        const key = node.textContent.trim();
        if (SETTINGS_RU[key]) entries.push({ node, key, original: node.textContent, last: node.textContent });
    }
    for (const node of root.querySelectorAll('[aria-label], [title]')) {
        for (const name of ['aria-label', 'title']) {
            const original = node.getAttribute(name);
            if (SETTINGS_RU[original]) attributes.push({ node, name, original });
        }
    }
    return (language) => {
        const russian = language === 'ru';
        root.lang = russian ? 'ru' : 'en';
        for (const entry of entries) {
            if (entry.node.textContent !== entry.last) continue;
            const text = russian ? entry.original.replace(entry.key, SETTINGS_RU[entry.key]) : entry.original;
            entry.node.textContent = text;
            entry.last = text;
        }
        for (const { node, name, original } of attributes) {
            node.setAttribute(name, russian ? SETTINGS_RU[original] : original);
        }
    };
}
