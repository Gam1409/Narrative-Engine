'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const directory = path.resolve(process.cwd(), process.argv[2] || 'tests');
const files = fs.readdirSync(directory).filter(name => /\.test\.(?:js|mjs)$/.test(name)).sort().map(name => path.join(directory, name));
if (!files.length) throw new Error(`No test files in ${directory}`);
const result = spawnSync(process.execPath, ['--test', ...files], { stdio: 'inherit' });
if (result.error) throw result.error;
process.exitCode = result.status ?? 1;
